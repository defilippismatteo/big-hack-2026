import {createRequire} from 'node:module';
import {resolve,dirname} from 'node:path';
import {fileURLToPath} from 'node:url';
const runtime=process.argv[2]??'/tmp/adera-motion-runtime';
const {chromium}=createRequire(resolve(runtime,'package.json'))('playwright-core');
import fs from 'node:fs';
const base=resolve(dirname(fileURLToPath(import.meta.url)),'../public/motion');
const browser=await chromium.launch({executablePath:'/Applications/Google Chrome.app/Contents/MacOS/Google Chrome',headless:true});
const page=await browser.newPage({viewport:{width:1440,height:1080}}),errors=[];
page.on('pageerror',e=>errors.push(e.message));
await page.goto('file://'+base+'/studio.html');
await page.waitForSelector('#stage svg');await page.evaluate(()=>document.fonts.ready);
const result={};
result.sceneButtons=await page.locator('.scene-tabs button').count();
await page.locator('#play').click();
result.pauseWorks=await page.evaluate(()=>document.querySelector('#stage').getAnimations({subtree:true}).every(a=>a.playState==='paused'));
await page.locator('.scene-tabs button').nth(1).click();
await page.waitForSelector('svg.decision');
await page.locator('#seek').fill('6');await page.locator('#seek').dispatchEvent('input');
result.seekWorks=await page.evaluate(()=>document.querySelector('#stage').getAnimations({subtree:true}).every(a=>Math.abs(a.currentTime-6000)<1));
result.percentagesPresent=(await page.locator('#stage').textContent()).includes('10,1%');
await page.locator('#speed').selectOption('1.5');
result.speedWorks=await page.evaluate(()=>document.querySelector('#stage').getAnimations({subtree:true}).every(a=>a.playbackRate===1.5));
await page.locator('#clean').click();result.cleanMode=await page.locator('body').getAttribute('class')==='clean';
await page.keyboard.press('Escape');result.escapeCleanMode=await page.locator('body').getAttribute('class')!== 'clean';
await page.locator('.scene-tabs button').nth(2).click();await page.waitForSelector('svg.interview');
await page.locator('#seek').fill('7.4');await page.locator('#seek').dispatchEvent('input');
result.interviewLiteral=(await page.locator('#stage').textContent()).includes('Apprezzo molto il riferimento');
await page.locator('.scene-tabs button').nth(0).click();await page.waitForSelector('svg.routing');
result.noAnimationLeak=(await page.evaluate(()=>document.querySelector('#stage').getAnimations({subtree:true}).length))>0;
await page.locator('#sequence').click();
await page.waitForSelector('svg.routing');
await page.evaluate(()=>document.querySelector('#stage').getAnimations({subtree:true}).forEach(a=>a.currentTime=8001));
await page.waitForSelector('svg.decision');
await page.evaluate(()=>document.querySelector('#stage').getAnimations({subtree:true}).forEach(a=>a.currentTime=8001));
await page.waitForSelector('svg.interview');
await page.evaluate(()=>document.querySelector('#stage').getAnimations({subtree:true}).forEach(a=>a.currentTime=8001));
await page.waitForFunction(()=>document.querySelector('#sequence').getAttribute('aria-pressed')==='false');
result.sequenceCompletes=await page.evaluate(()=>document.querySelector('#stage').getAnimations({subtree:true}).every(a=>a.playState==='paused'));
await page.setViewportSize({width:390,height:844});result.noPageOverflow=await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth);
await page.emulateMedia({reducedMotion:'reduce'});await page.reload();await page.waitForSelector('#stage svg');
result.reducedMotion=await page.evaluate(()=>document.querySelector('#stage').getAnimations({subtree:true}).length===0&&document.querySelector('#play').disabled);
result.errors=errors;
fs.writeFileSync(base+'/studio-check.json',JSON.stringify(result,null,2)+'\n');console.log(JSON.stringify(result));
await browser.close();
if(Object.entries(result).some(([k,v])=>k!=='sceneButtons'&&k!=='errors'&&!v)||errors.length)process.exitCode=1;
